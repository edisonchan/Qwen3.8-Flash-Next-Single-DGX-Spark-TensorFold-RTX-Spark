# menu.ps1 -- the one interactive entry point for the Windows ARM64 release.
# Everything below asks instead of expecting command-line arguments; the underlying
# scripts (start.ps1 / stop.ps1 / scripts\download-model.ps1 / scripts\build-gpl-video.ps1)
# keep their full CLI, this file only drives them.
#
# Double-click menu.bat, or run:  powershell -ExecutionPolicy Bypass -File .\menu.ps1
# Nothing here installs software; every action is one of the scripts shipped in this folder.
# UTF-8 with BOM (Windows PowerShell 5.1 reads Chinese labels from it).

$ErrorActionPreference = 'Continue'
$Root = $PSScriptRoot
# Spawn children on the same host that runs this menu: pwsh (7+) launches pwsh, Windows
# PowerShell (5.1) launches powershell.exe. [Environment]::ProcessPath exists only in 7+.
if ($PSVersionTable.PSEdition -eq 'Core') { $PsExe = [Environment]::ProcessPath }
else { $PsExe = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe' }
$EnvFile = Join-Path $Root '.env'

function Say { param([string]$m) Write-Host "[menu] $m" }
function SayErr { param([string]$m) Write-Host "[menu] $m" -ForegroundColor Red }
function Pause-Back { Write-Host ''; Read-Host '[menu] 按回车返回主菜单 / press Enter to go back' | Out-Null }

# ---------------------------------------------------------------- .env helpers (KEY=value, never executed)
function Read-EnvValue {
  param([string]$Key, [string]$Default = '')
  if (Test-Path -LiteralPath $EnvFile) {
    foreach ($line in (Get-Content -LiteralPath $EnvFile -Encoding UTF8)) {
      if ($line -match "^\s*(?:export\s+)?$Key\s*=\s*(.*)$") {
        $v = $Matches[1].Trim()
        if ($v -match '^"([^"]*)"$' -or $v -match "^'([^']*)'$") { $v = $Matches[1] }
        $v = ($v -replace '#.*$', '').Trim()
        if ($v) { return $v }
        break
      }
    }
  }
  return $Default
}

function Set-EnvValue {
  # Replace (or append) one KEY=value line in .env; creates the file when missing.
  param([string]$Key, [string]$Value)
  $lines = @()
  if (Test-Path -LiteralPath $EnvFile) { $lines = @(Get-Content -LiteralPath $EnvFile -Encoding UTF8) }
  else { $lines = @('# Generated by menu.ps1 -- environment variables set in the shell win over these lines.') }
  $done = $false
  $out = foreach ($line in $lines) {
    if ($line -match "^\s*(?:export\s+)?$Key\s*=") { if (-not $done) { $done = $true; "$Key=$Value" } else { continue } }
    else { $line }
  }
  $out = @($out)
  if (-not $done) { $out += "$Key=$Value" }
  [System.IO.File]::WriteAllLines($EnvFile, $out, (New-Object System.Text.UTF8Encoding($false)))
  Say "$Key=$Value -> .env"
}

function Get-Effective {
  # A setting the way config.ps1 resolves it: environment first, then .env, then the default.
  param([string]$Key, [string]$Default)
  $v = [Environment]::GetEnvironmentVariable($Key)
  if (-not [string]::IsNullOrEmpty($v)) { return $v }
  return (Read-EnvValue $Key $Default)
}

# ---------------------------------------------------------------- child runner
function Run-Child {
  # Run one of the shipped scripts in a child powershell so an `exit` inside it cannot
  # close the menu; output streams straight to this console.
  param([string]$Script, [string[]]$Arguments = @())
  if (-not (Test-Path -LiteralPath $Script)) { SayErr "not found: $Script"; return 1 }
  # Out-Host keeps the child's streamed output visible: a native child's stdout would
  # otherwise land on this function's success stream and be dropped by [void](...).
  & $PsExe -NoProfile -ExecutionPolicy Bypass -File $Script @Arguments | Out-Host
  return $LASTEXITCODE
}

# ---------------------------------------------------------------- actions
function Do-Start {
  Say '启动服务 / starting the server (first load takes about a minute / 首次加载约一分钟)...'
  [void](Run-Child (Join-Path $Root 'start.ps1'))
}
function Do-Restart {
  Say '重启服务 / restarting...'
  [void](Run-Child (Join-Path $Root 'start.ps1') @('restart'))
}
function Do-Stop {
  [void](Run-Child (Join-Path $Root 'stop.ps1'))
}

function Do-Status {
  $port = Get-Effective 'PORT' '8888'
  $distDir = Get-Effective 'DIST_DIR' (Join-Path $Root 'tensorfold\dist')
  $exe = Join-Path $distDir 'native\bin\tensorfold-native.exe'
  $modelDir = Get-Effective 'MODEL_DIR' 'D:\llm\models\Qwen3.8-Flash-Next-FP4-Local'
  $stateDir = Get-Effective 'STATE_DIR' (Join-Path $env:USERPROFILE '.local\state\qwen38-flash-next-tf')
  $pidFile = Join-Path $stateDir 'server.pid'

  if (Test-Path -LiteralPath $exe) { Say ('engine    OK  {0}' -f $exe) } else { SayErr ('engine    MISSING  {0}（先下载/解压 / download the release first）' -f $exe) }
  if (Test-Path -LiteralPath (Join-Path $modelDir 'config.json')) { Say ('weights   OK  {0}' -f $modelDir) } else { SayErr ('weights   MISSING  {0}（菜单 4 下载 / download from menu option 4）' -f $modelDir) }

  $running = $false
  if (Test-Path -LiteralPath $pidFile) {
    $srvPid = 0
    if ([int]::TryParse((Get-Content -LiteralPath $pidFile -First 1).Trim(), [ref]$srvPid)) {
      $proc = Get-Process -Id $srvPid -ErrorAction SilentlyContinue
      if ($proc) { $running = $true; Say ("server    running  PID {0} ({1})" -f $srvPid, $proc.ProcessName) }
    }
  }
  if (-not $running) { Say 'server    not running（菜单 1 启动 / start from menu option 1）' }

  try {
    $resp = Invoke-WebRequest -Uri "http://127.0.0.1:$port/v1/models" -TimeoutSec 3 -UseBasicParsing
    $json = $resp.Content | ConvertFrom-Json
    $name = $json.data[0].id
    Say ("API       answering  http://127.0.0.1:$port/v1  (model: $name)")
    $lan = $null
    try {
      $lan = (Get-NetIPAddress -AddressFamily IPv4 -ErrorAction Stop |
              Where-Object { $_.IPAddress -notlike '127.*' -and $_.IPAddress -notlike '169.254.*' } |
              Select-Object -First 1).IPAddress
    } catch { }
    if ($lan) { Say ("LAN       http://${lan}:$port/v1  (局域网访问需放行防火墙 / see README firewall rule)" ) }
  } catch {
    Say 'API       not answering on this port yet'
  }
}

function Do-Download {
  Write-Host ''
  Write-Host '  下载模型权重 / Download the FP4 checkpoint (~95 GiB, 断点续传 safe to re-run)'
  Write-Host '    [1] 自动选择源 / auto  (ping 4s 择优, 默认/recommended)'
  Write-Host '    [2] Hugging Face'
  Write-Host '    [3] ModelScope（国内通常更快 / usually faster in China）'
  Write-Host '    [4] 只列清单不下载 / list files only'
  Write-Host '    [0] 返回 / back'
  $c = (Read-Host '  选择 / choice').Trim()
  if ($c -eq '0' -or -not $c) { return }
  $source = 'auto'
  if ($c -eq '2') { $source = 'hf' } elseif ($c -eq '3') { $source = 'modelscope' }
  if ($c -eq '4') {
    [void](Run-Child (Join-Path $Root 'scripts\download-model.ps1') @('-Source', $source, '-ListOnly'))
    return
  }
  $defDir = Get-Effective 'MODEL_DIR' 'D:\llm\models\Qwen3.8-Flash-Next-FP4-Local'
  $target = Read-Host "  权重存放目录 / target directory（回车用默认 / Enter for default）`n    [$defDir]"
  if (-not $target) { $target = $defDir }
  $target = $target.Trim().Trim('"')
  $drive = ($target -split '\\')[0]
  if ($drive -match '^[A-Za-z]:' -and -not (Test-Path -LiteralPath ($drive + '\'))) {
    SayErr "驱动器不存在 / drive not found: $drive"
    return
  }
  Write-Host ''
  $code = Run-Child (Join-Path $Root 'scripts\download-model.ps1') @('-Source', $source, '-TargetDir', $target)
  if ($code -eq 0) {
    $cur = Read-EnvValue 'MODEL_DIR' ''
    if ($cur -ne $target) {
      $a = Read-Host "  把 MODEL_DIR=$target 写入 .env 吗？/ write this into .env? [Y/n]"
      if ($a -notmatch '^[nN]') { Set-EnvValue 'MODEL_DIR' $target }
    }
  }
}

function Do-VideoBuild {
  Write-Host ''
  Write-Host '  构建视频解码栈（可选）/ build the GPL video stack (optional)'
  Write-Host '  需要本机已有 Zig 0.17.0 / needs a local Zig 0.17.0. 本菜单不安装任何软件 / nothing is installed here.'
  $zig = Read-Host "  Zig 路径 / Zig path（回车用默认 / Enter for default）`n    [D:\building\zig-aarch64-windows-0.17.0\zig.exe]"
  $args1 = @()
  if ($zig) { $args1 = @('-ZigExe', $zig.Trim().Trim('"')) }
  [void](Run-Child (Join-Path $Root 'scripts\build-gpl-video.ps1') $args1)
}

# ---------------------------------------------------------------- menu loop
function Show-Menu {
  Clear-Host
  Write-Host ''
  Write-Host '   TensorFold · Qwen3.8 Flash Next · Windows ARM64  —  选单 / menu' -ForegroundColor Magenta
  Write-Host '   -------------------------------------------------------------' -ForegroundColor DarkGray
  Write-Host '     [1] 启动服务        Start the server'
  Write-Host '     [2] 停止服务        Stop the server'
  Write-Host '     [3] 重启服务        Restart the server'
  Write-Host '     [4] 下载模型权重    Download the weights (auto HF / ModelScope)'
  Write-Host '     [5] 查看状态        Status (engine / weights / server / API)'
  Write-Host '     [6] 构建视频栈(选)  Build the video stack (optional)'
  Write-Host '     [0] 退出            Exit'
  Write-Host ''
}

while ($true) {
  Show-Menu
  $c = (Read-Host '  请输入编号 / enter a number').Trim()
  switch ($c) {
    '1' { Do-Start; Pause-Back }
    '2' { Do-Stop; Pause-Back }
    '3' { Do-Restart; Pause-Back }
    '4' { Do-Download; Pause-Back }
    '5' { Do-Status }
    '6' { Do-VideoBuild; Pause-Back }
    '0' { Write-Host '[menu] 再见 / bye'; exit 0 }
    default { Say '无效编号，请重新输入 / invalid choice' ; Start-Sleep -Seconds 1 }
  }
}
